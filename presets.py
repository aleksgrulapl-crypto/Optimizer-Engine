# Pine fallback for tickers without a dedicated row (the 30M table uses period 12).
DEFAULT_PRESETS = {
    "15M": (3.0, 10, 1.4, 2.4, 200, 1.5),
    "30M": (3.0, 12, 1.4, 2.4, 200, 1.5),
    "60M": (3.0, 10, 1.4, 2.4, 200, 1.5),
}
_TIMEFRAME_INDEX = {"15M": 0, "30M": 1, "60M": 2}


def normalize_timeframe(timeframe: str = "15M") -> str:
    normalized = str(timeframe).strip().upper()
    aliases = {
        "15M": "15M",
        "30M": "30M",
        "60M": "60M",
        "1H": "60M",
        "15MIN": "15M",
        "30MIN": "30M",
        "60MIN": "60M",
    }
    normalized = aliases.get(normalized, normalized)
    if normalized not in {"15M", "30M", "60M"}:
        raise ValueError("timeframe must be '15M', '30M', or '60M'")
    return normalized


def get_presets(ticker: str, timeframe: str = "15M") -> Dict[str, float]:
    ticker = ticker.strip().upper()
    timeframe = normalize_timeframe(timeframe)

    if ticker in PRESETS:
        values = PRESETS[ticker][_TIMEFRAME_INDEX[timeframe]]
    else:
        values = DEFAULT_PRESETS[timeframe]
    keys = ("stMultiplier", "stPeriod", "atrSLmult", "atrTPmult", "emaLen", "maxEntryCandleATR")
    return dict(zip(keys, values))